#!/bin/sh
# Builds a link-time stub libSz.so for Android from the Senzing C headers, so the JNI library
# can be linked before an Android libSz is available. The stub only satisfies the linker (its
# functions do nothing): at run time the app loads the real libSz.so, whose SONAME matches.
#
# Usage: android-link-stub.sh <runtime er dir> <output dir> <android api level>
# Needs ANDROID_NDK_HOME.
set -eu
er_dir=$1
out_dir=$2
api=$3
: "${ANDROID_NDK_HOME:?set ANDROID_NDK_HOME to the Android NDK}"
clang=$(ls "$ANDROID_NDK_HOME"/toolchains/llvm/prebuilt/*/bin/aarch64-linux-android"$api"-clang | head -n 1)
mkdir -p "$out_dir"
source_file="$out_dir/libSz-stub.c"
{
    echo "/* Generated by android-link-stub.sh from $er_dir/sdk/c: link-time stub, never run. */"
    grep -ho '_DLEXPORT[^(]*[[:space:]*]\(Sz[A-Za-z0-9_]*\)[[:space:]]*(' "$er_dir"/sdk/c/*.h "$er_dir"/sdk/c/szhelpers/*.h |
        sed -E 's/.*[[:space:]*](Sz[A-Za-z0-9_]*)[[:space:]]*\($/\1/' | sort -u |
        while read -r name; do echo "void $name(void) {}"; done
} > "$source_file"
"$clang" -shared -fPIC -Wl,-soname,libSz.so -o "$out_dir/libSz.so" "$source_file"
echo "$out_dir/libSz.so: $(grep -c '^void' "$source_file") stub functions"
