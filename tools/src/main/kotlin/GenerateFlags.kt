// Generates the Kotlin SzFlags value class, its constants and SzFlagUsageGroup from the
// language-neutral szflags.json that ships with every Senzing runtime.
//
// Usage: GenerateFlags <szflags.json> <output SzFlags.kt>

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import java.io.File

/** One szflags.json entry. */
data class Flag(
    val symbol: String,
    val value: Long,
    val bits: List<Int>,
    val union: List<String>?,
    val altGroups: List<String>,
)

fun parse(file: File): List<Flag> =
    Json.parseToJsonElement(file.readText()).jsonArray.map { element ->
        val entry = element.jsonObject
        val definition = entry.getValue("definition")
        Flag(
            symbol = entry.getValue("symbol").jsonPrimitive.content,
            value = entry.getValue("value").jsonPrimitive.long,
            bits = entry.getValue("bits").jsonArray.map { it.jsonPrimitive.content.toInt() },
            union = (definition as? JsonArray)?.map { it.jsonPrimitive.content },
            altGroups = entry.getValue("altGroups").jsonArray.map { it.jsonPrimitive.content },
        )
    }

/** `SZ_ENTITY_INCLUDE_ENTITY_NAME` -> `ENTITY_INCLUDE_ENTITY_NAME`. */
fun constantName(symbol: String): String = symbol.removePrefix("SZ_")

/** `SzWhyRecordInEntityFlags` -> `WHY_RECORD_IN_ENTITY`. */
fun groupName(altGroup: String): String =
    altGroup
        .removePrefix("Sz")
        .removeSuffix("Flags")
        .replace(Regex("([a-z0-9])([A-Z])"), "$1_$2")
        .uppercase()

fun hex(value: Long): String {
    val digits = java.lang.Long.toHexString(value).uppercase().padStart(16, '0')
    return "0x" + digits.chunked(4).joinToString("_") + "L"
}

fun kdocGroups(flag: Flag): String =
    flag.altGroups.joinToString(", ") { "[SzFlagUsageGroup.${groupName(it)}]" }

fun generate(flags: List<Flag>): String {
    val out = StringBuilder()
    out.append(
        """
        |// @generated by tools/src/main/kotlin/GenerateFlags.kt from szflags.json. DO NOT EDIT.
        |//
        |// Regenerate from an installed Senzing runtime with:
        |//   ./gradlew :tools:generateFlags
        |
        |package io.github.brianmacy.sz
        |
        |/**
        | * Bit flags that control what the engine returns, mirroring the C# `SzFlag`.
        | *
        | * The named constants (for example [ENTITY_DEFAULT_FLAGS] and [WITH_INFO]) are generated
        | * from the `szflags.json` file that ships with the Senzing runtime. Every engine method
        | * defaults its `flags` argument to the matching `..._DEFAULT_FLAGS` constant. Combine flags
        | * with `or` (or `+`), and test them with `in`:
        | *
        | * ```kotlin
        | * engine.getEntity(entityId, SzFlags.ENTITY_INCLUDE_ENTITY_NAME or SzFlags.ENTITY_INCLUDE_RECORD_DATA)
        | * engine.addRecord("CUSTOMERS", "1", json, SzFlags.WITH_INFO)
        | * ```
        | *
        | * Use [NO_FLAGS] for no flags. [SzFlagUsageGroup] lists which flags each method accepts.
        | *
        | * @property value The flag bits.
        | */
        |@JvmInline
        |public value class SzFlags(
        |    public val value: Long,
        |) {
        |    /** The union of these flags and [other]. */
        |    public infix fun or(other: SzFlags): SzFlags = SzFlags(value or other.value)
        |
        |    /** The flags in both these flags and [other]. */
        |    public infix fun and(other: SzFlags): SzFlags = SzFlags(value and other.value)
        |
        |    /** The union of these flags and [other]. */
        |    public operator fun plus(other: SzFlags): SzFlags = this or other
        |
        |    /** These flags without the flags in [other]. */
        |    public operator fun minus(other: SzFlags): SzFlags = SzFlags(value and other.value.inv())
        |
        |    /** Whether every flag in [other] is set here (`other in flags`). */
        |    public operator fun contains(other: SzFlags): Boolean = value and other.value == other.value
        |
        |    /** Whether no flag is set. */
        |    public fun isEmpty(): Boolean = value == 0L
        |
        |    override fun toString(): String =
        |        "SzFlags(0x" +
        |            java.lang.Long
        |                .toHexString(value)
        |                .uppercase() + ")"
        |
        |    /** The named flags, generated from `szflags.json`. */
        |    public companion object {
        |        /** The default flags for [SzEngine.processRedoRecord]: none (C# `SzRedoDefaultFlags`, not in `szflags.json`). */
        |        public val REDO_DEFAULT_FLAGS: SzFlags = SzFlags(0L)
        |
        """.trimMargin(),
    )
    // trimMargin drops the trailing blank line; keep one before the first flag (as ktlint does).
    out.append("\n")
    for (flag in flags) {
        val name = constantName(flag.symbol)
        val definition =
            flag.union?.joinToString(", ", prefix = ": the union of ") { "`$it`" }
                ?: flag.bits.singleOrNull()?.let { " (`1 << $it`)" }
                ?: " (`${flag.value}`)"
        out.append("        /**\n         * `${flag.symbol}`$definition.\n")
        if (flag.altGroups.isNotEmpty()) {
            out.append("         *\n         * Usage groups: ${kdocGroups(flag)}.\n")
        }
        out.append("         */\n        public val $name: SzFlags = SzFlags(${hex(flag.value)})\n\n")
    }
    out.setLength(out.length - 1)
    out.append("    }\n}\n\n")

    val groups = flags.flatMap { it.altGroups }.distinct().sorted()
    out.append(
        """
        |/**
        | * The flag usage groups of `szflags.json`: which flags apply to which engine methods.
        | *
        | * @property altName The group's `szflags.json` name (for example `SzEntityFlags`).
        | * @property allFlags Every flag that applies to this group (empty when the group's methods
        | *   take no flags).
        | */
        |public enum class SzFlagUsageGroup(
        |    public val altName: String,
        |    public val allFlags: SzFlags,
        |) {
        |
        """.trimMargin(),
    )
    for (group in groups) {
        val mask = flags.filter { group in it.altGroups && it.bits.size == 1 }.fold(0L) { acc, f -> acc or f.value }
        out.append("    /** `$group`. */\n    ${groupName(group)}(\"$group\", SzFlags(${hex(mask)})),\n\n")
    }
    out.setLength(out.length - 1)
    out.append(
        """
        |    ;
        |
        |    public companion object {
        |        /** The group with a `szflags.json` name, or null. */
        |        public fun fromAltName(altName: String): SzFlagUsageGroup? = entries.firstOrNull { it.altName == altName }
        |    }
        |}
        |
        """.trimMargin(),
    )
    return out.toString()
}

fun main(args: Array<String>) {
    require(args.size == 2) { "usage: GenerateFlags <szflags.json> <output SzFlags.kt>" }
    val output = File(args[1])
    output.writeText(generate(parse(File(args[0]))))
    println("wrote $output")
}
